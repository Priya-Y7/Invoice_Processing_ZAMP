"""PDF run report and vendor letter (ReportLab)."""
import io
import json

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from .util import inr

NAVY, INDIGO = colors.HexColor("#0B1220"), colors.HexColor("#3B5BDB")
VCOL = {"Approve": colors.HexColor("#1F9D55"), "Review": colors.HexColor("#D98A00"), "Reject": colors.HexColor("#D64545")}
RCOL = {"pass": "#1F9D55", "warn": "#D98A00", "fail": "#D64545", "error": "#7048E8", "skipped": "#8A94A6"}
ss = getSampleStyleSheet()
H = ParagraphStyle("H", parent=ss["Heading2"], textColor=NAVY, fontSize=12, spaceBefore=10, spaceAfter=4)
B = ParagraphStyle("B", parent=ss["BodyText"], fontSize=9, leading=12)
S = ParagraphStyle("S", parent=B, fontSize=8, leading=10, textColor=colors.HexColor("#4A5568"))


def _esc(t):
    return str(t if t is not None else "—").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def run_report(run, result):
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=14 * mm, bottomMargin=14 * mm,
                            title=f"InvoiceIQ run report {run.run_id}")
    d = result["decision"]
    F = (result.get("extraction") or {}).get("fields", {})
    el = []
    el.append(Paragraph("<b>InvoiceIQ</b> · Run report", ParagraphStyle("t", parent=ss["Title"], fontSize=16, textColor=NAVY, alignment=0)))
    el.append(Paragraph(f"Run {run.run_id} · {_esc(run.filename)} · processed {run.finished_at:%d %b %Y %H:%M} UTC", S))
    v = run.final_decision or d["verdict"]
    badge = Table([[Paragraph(f"<font color='white'><b>{v.upper()}</b></font>", ParagraphStyle("v", fontSize=18, alignment=1)),
                    Paragraph(_esc(d["reason"]), B)]], colWidths=[38 * mm, 140 * mm])
    badge.setStyle(TableStyle([("BACKGROUND", (0, 0), (0, 0), VCOL[v]), ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                               ("BOX", (0, 0), (-1, -1), 0.6, VCOL[v]), ("TOPPADDING", (0, 0), (-1, -1), 8), ("BOTTOMPADDING", (0, 0), (-1, -1), 8)]))
    el += [Spacer(1, 6), badge]
    if run.final_decision != d["verdict"]:
        el.append(Paragraph(f"Pipeline verdict was <b>{d['verdict']}</b>; changed by a human override (see audit log).", S))
    el.append(Paragraph("Extracted invoice", H))
    rows = [["Invoice number", F.get("invoice_number"), "Invoice date", F.get("invoice_date")],
            ["Vendor", F.get("vendor_name"), "Vendor GSTIN", F.get("vendor_gstin")],
            ["PO reference", F.get("po_reference") or "(not printed)", "Matched PO", (result.get("po") or {}).get("matched_po")],
            ["Subtotal", inr(F.get("subtotal")), "Tax", inr(F.get("tax_total"))],
            ["Total", inr(F.get("total_amount")), "Confidence", f"{(result.get('extraction') or {}).get('overall_confidence') or 0:.0%}"]]
    t = Table([[Paragraph(_esc(c), B) for c in r] for r in rows], colWidths=[30 * mm, 59 * mm, 30 * mm, 59 * mm])
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#D5DAE3")), ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F5F7FA")),
                           ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#F5F7FA"))]))
    el.append(t)
    if d.get("trail"):
        el.append(Paragraph("Why this decision (rule trail)", H))
        rows = [["Rule", "Level", "Finding"]] + [[x["rule"], x["level"], Paragraph(_esc(x["detail"]), S)] for x in d["trail"]]
        t = Table(rows, colWidths=[16 * mm, 20 * mm, 142 * mm], repeatRows=1)
        t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), NAVY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white), ("FONTSIZE", (0, 0), (-1, -1), 8),
                               ("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#D5DAE3")), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
        el.append(t)
    el.append(Paragraph("The nine stages", H))
    for st in result["stages"]:
        el.append(Paragraph(f"<font color='{RCOL.get(st['status'], '#000')}'><b>{st['stage_no']} · {_esc(st['stage_name'])}</b> "
                            f"[{st['status']}] {st['duration_ms']} ms</font> — {_esc(st['summary'])}", B))
        for c in st["checks"]:
            el.append(Paragraph(f"&nbsp;&nbsp;&nbsp;<font color='{RCOL.get(c['result'], '#000')}'>{c['result'].upper()}</font> {c['rule']} {_esc(c['label'])}: {_esc(c['detail'])}", S))
    el.append(Spacer(1, 8))
    el.append(Paragraph("Generated by InvoiceIQ. Every verdict comes from deterministic rules; see rule ids for traceability.", S))
    doc.build(el)
    return buf.getvalue()


def vendor_letter(run, result):
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=22 * mm, rightMargin=22 * mm, topMargin=22 * mm, bottomMargin=20 * mm)
    msg = (result["decision"].get("vendor_message") or "No vendor message is needed for this decision.")
    el = [Paragraph("Accounts Payable", ParagraphStyle("h", parent=ss["Title"], fontSize=15, textColor=NAVY, alignment=0)),
          Paragraph(f"Re: invoice {_esc(run.invoice_number or 'n/a')} · reference {run.run_id}", S), Spacer(1, 12)]
    for para in msg.split("\n"):
        el.append(Paragraph(_esc(para) if para.strip() else "&nbsp;", ParagraphStyle("l", parent=B, fontSize=10.5, leading=15)))
    doc.build(el)
    return buf.getvalue()
